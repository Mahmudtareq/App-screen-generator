import type { Metadata } from "next";
import { Geist, Geist_Mono } from "next/font/google";

import { Toaster } from "@/components/ui/sonner";

import "./globals.css";

// UI chrome only. Canvas text uses the separate, literally-named families
// declared in globals.css — see config/fonts.ts for why.
// The variable name must be `--font-sans`: that is what shadcn's generated
// `@theme inline` block in globals.css maps Tailwind's font-sans onto.
const geistSans = Geist({
  variable: "--font-sans",
  subsets: ["latin"],
});

const geistMono = Geist_Mono({
  variable: "--font-geist-mono",
  subsets: ["latin"],
});

export const metadata: Metadata = {
  title: "Mockup Studio",
  description: "Drop a screenshot into a device frame and export a polished mockup.",
};

export default function RootLayout({ children }: LayoutProps<"/">) {
  return (
    <html
      lang="en"
      className={`${geistSans.variable} ${geistMono.variable} h-full antialiased`}
    >
      <body className="min-h-full flex flex-col">
        {children}
        <Toaster />
      </body>
    </html>
  );
}
